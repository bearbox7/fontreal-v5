import assert from 'node:assert/strict';
import {readOutline,writeOutline,outlineSVG,moveAnchor,moveHandle,setAnchorMode,splitEdge,deleteAnchor} from '../lib/font/node-editor.ts';
const path='M100 100L400 100C500 100 500 500 400 500L100 500Z';
const shape=readOutline(path);
assert.equal(shape[0].nodes[0].y,780);
const saved=readOutline(writeOutline(shape));
assert.deepEqual(saved,shape);
const moved=moveAnchor(shape,0,1,{x:410,y:790});
assert.deepEqual(moved[0].nodes[1].outgoing,{x:510,y:790});
assert.deepEqual(shape[0].nodes[1],{x:400,y:780,outgoing:{x:500,y:780}});
const smooth=setAnchorMode(shape,0,1,'smooth');
const adjusted=moveHandle(smooth,0,1,'outgoing',{x:450,y:830});
const a=adjusted[0].nodes[1],cross=(a.incoming.x-a.x)*(a.outgoing.y-a.y)-(a.incoming.y-a.y)*(a.outgoing.x-a.x);
assert.ok(Math.abs(cross)<1e-7);
assert.equal(moveHandle(smooth,0,1,'outgoing',{x:450,y:830},true)[0].nodes[1].smooth,false);
const split=splitEdge(shape,0,1);
assert.equal(split[0].nodes.length,5);
assert.equal(split[0].nodes[2].x,475);
assert.equal(split[0].nodes[2].y,580);
assert.equal(deleteAnchor(split,0,2)[0].nodes.length,4);
const closed=readOutline('M0 0C0 50 50 100 100 100C100 50 50 0 0 0Z');
assert.equal(closed[0].nodes.length,2);
assert.deepEqual(readOutline(writeOutline(closed)),closed);
const quadratic=readOutline('M0 0Q50 100 100 0Z');
assert.equal(quadratic[0].nodes.length,2);
assert.match(outlineSVG(quadratic),/C/);
assert.equal(outlineSVG(readOutline(writeOutline(quadratic))),outlineSVG(quadratic));
console.log('Node editor checks passed: coordinate inversion, closed contour roundtrip, cubic/quadratic preservation, anchor+handles, smooth/Alt break, exact cubic split and deletion.');
